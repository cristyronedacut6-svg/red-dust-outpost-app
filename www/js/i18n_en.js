// helper used by each language file: pairs its list with the English one, then hands it to I18N.more()
window.I18N_LOAD = function (lang, list, pats) { if (!window.I18N || !I18N.more) return; const E = window.I18N_EN, P = window.I18N_PAT, d = {}, p = {};
  if (list.length !== E.length) { console.warn('i18n ' + lang + ': ' + list.length + ' lines for ' + E.length + ' English lines'); }
  E.forEach((e, i) => { if (list[i]) d[e] = list[i]; }); (pats || []).forEach((o, i) => { if (o && P[i]) p[P[i]] = o; }); I18N.more(lang, d, p); };
